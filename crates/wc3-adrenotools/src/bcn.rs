//! BCn enabler — Rust port of `src/bcenabler.cpp`.
//!
//! The donor patches Qualcomm's internal format-conversion function so that the
//! Adreno blob reports support for BCn compressed textures. The mechanism:
//!
//! 1. Find the first `BL` in `vkGetPhysicalDeviceFormatProperties` and follow it to
//!    the internal conversion function.
//! 2. Find `mov w0, wzr` (the "unknown format" default result) inside it.
//! 3. Map a free page next to the blob, copy in a generated `if`-chain that maps
//!    BCn formats (131..146) to Adreno internal formats (71..99), and branch the
//!    default result to that page.
//!
//! The donor ships the `if`-chain as a 264-byte blob produced by
//! `aarch64-linux-gnu-gcc` + `objcopy` + `bin2c` (`src/bcenabler_patch.s`,
//! `gen/bcenabler_patch.h`). This port **generates the same instructions at
//! runtime** from the `(input, output)` table, so no C toolchain or binary blob is
//! part of the build. A test pins the generated bytes against the donor blob.
//!
//! Three safety deltas, all observable:
//! * the donor scans `.text` without bounds; this port bounds every scan to the
//!   containing mapping and returns `Err` instead of running off the end;
//! * the donor maps the patch page with `MAP_FIXED` (clobbering whatever is there
//!   if a race occurred); this port uses `MAP_FIXED_NOREPLACE` where the kernel
//!   supports it and re-reads the maps once on `EEXIST`;
//! * the donor patches the driver word under `PROT_READ|WRITE|EXEC`; this port
//!   uses a strict W^X window — `RX -> RW (no X) -> write -> icache sync -> RX`
//!   ([`patch_code_word`]) — serialised by a process-wide guard. The page holding
//!   the driver's default result is never writable and executable at the same
//!   time, and `/proc/self/maps` is sampled at every stage so the window is
//!   provable (`audit_wx_probe` example, WC3-I-004).
//!
//! Quiescence policy: the enabler runs from the driver-open path, before any
//! render thread calls the driver's format-conversion function; the guard makes a
//! concurrent second enabler a controlled [`BcnError::Busy`], and the write
//! window lasts one `mprotect` + one word store. Threads that are already
//! executing the page are the one case this cannot stop — there is no portable
//! stop-the-world in-process, and the alternative (patching under RWX) is the
//! defect this replaces.

