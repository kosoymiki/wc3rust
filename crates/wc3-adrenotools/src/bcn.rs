/// `ClearResultSignature` from `bcenabler.cpp:89` — `mov w0, wzr`.
pub const CLEAR_RESULT_SIGNATURE: u32 = 0x2a1f_03e0;
/// `PatchReturnFixupMagic` from `bcenabler.cpp:104`.
pub const PATCH_RETURN_FIXUP: u32 = 0xffff_ffff;

/// `(BCn input format, Adreno internal format)` pairs, decoded from the donor's
/// generated blob (`gen/bcenabler_patch.h`).
///
/// Order matters: the generated chain compares in this exact sequence.
pub const BCN_FORMAT_TABLE: &[(u32, u32)] = &[
    (131, 71),
    (133, 71),
    (132, 72),
    (134, 72),
    (135, 74),
    (136, 75),
    (137, 77),
    (138, 78),
    (139, 80),
    (140, 81),
    (141, 83),
    (142, 84),
    (143, 95),
    (144, 96),
    (145, 98),
    (146, 99),
];

/// `adrenotools_bcn_type` (`include/adrenotools/bcenabler.h:13-18`).
#[repr(u32)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BcnType {
    Incompatible = 0,
    Blob = 1,
    Patch = 2,
}

/// `adrenotools_get_bcn_type` (`bcenabler.cpp:12-20`).
pub fn get_bcn_type(major: u32, minor: u32, vendor_id: u32) -> BcnType {
    if vendor_id != 0x5143 || major != 512 {
        return BcnType::Incompatible;
    }
    if minor >= 514 {
        return BcnType::Blob;
    }
    BcnType::Patch
}

/// Generate the patch instructions.
///
/// Layout (66 words, exactly the donor blob):
/// for each entry `i`: `cmp w0,#in` / `b.ne +3` / `mov w0,#out` / `b fixup`,
/// then `mov w0,#0` (fall-through default) and the fixup word.
pub fn generate_patch_words() -> Vec<u32> {
    let count = BCN_FORMAT_TABLE.len();
    let fixup_index = 4 * count + 1;
    let mut words = Vec::with_capacity(fixup_index + 1);
    for (i, &(input, output)) in BCN_FORMAT_TABLE.iter().enumerate() {
        let base = 4 * i;
        words.push(aarch64::encode_cmp_imm(0, input));
        words.push(
            aarch64::encode_b_ne((base + 1) * 4, (base + 4) * 4)
                .expect("conditional branch inside the patch is always in range"),
        );
        words.push(aarch64::encode_movz(0, output as u16));
        words.push(
            aarch64::encode_b((base + 3) * 4, fixup_index * 4)
                .expect("patch return branch is always in range"),
        );
    }
    words.push(aarch64::encode_movz(0, 0));
    words.push(PATCH_RETURN_FIXUP);
    words
}

pub fn generate_patch_bytes() -> Vec<u8> {
    generate_patch_words()
        .into_iter()
        .flat_map(u32::to_le_bytes)
        .collect()
}

#[derive(Debug)]
pub enum BcnError {
    NullFunction,
    Maps(io::Error),
    NotMapped,
    NotExecutable,
    NoBranch,
    TargetNotMapped,
    TargetNotExecutable,
    NoClearResult,
    PatchTooLarge,
    NoFreePage,
    UnalignedFreePage,
    MapFailed(io::Error),
    Mprotect(io::Error),
    BranchOutOfRange(aarch64::EncodeError),
    /// Another enabler is inside its write window.
    Busy,
    /// A code patch must be 4-byte aligned (one AArch64 instruction).
    UnalignedWord,
}

impl fmt::Display for BcnError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::NullFunction => f.write_str("vkGetPhysicalDeviceFormatProperties is NULL"),
            Self::Maps(e) => write!(f, "cannot read /proc/self/maps: {e}"),
            Self::NotMapped => f.write_str("function pointer is not mapped"),
            Self::NotExecutable => f.write_str("function pointer is not executable"),
            Self::NoBranch => f.write_str("no BL instruction found in the target function"),
            Self::TargetNotMapped => f.write_str("BL target is not mapped"),
            Self::TargetNotExecutable => f.write_str("BL target is not executable"),
            Self::NoClearResult => f.write_str("format-conversion default result not found"),
            Self::PatchTooLarge => f.write_str("patch is larger than one page"),
            Self::NoFreePage => f.write_str("no free page near the driver"),
            Self::UnalignedFreePage => f.write_str("free page is not page aligned"),
            Self::MapFailed(e) => write!(f, "cannot map patch page: {e}"),
            Self::Mprotect(e) => write!(f, "cannot make driver code writable: {e}"),
            Self::BranchOutOfRange(e) => write!(f, "cannot encode patch branch: {e}"),
            Self::Busy => f.write_str("another BCn enabler holds the patch guard"),
            Self::UnalignedWord => f.write_str("code patch address is not 4-byte aligned"),
        }
    }
}

impl std::error::Error for BcnError {}

fn page_size() -> usize {
    // SAFETY: sysconf has no preconditions.
    let value = unsafe { libc::sysconf(libc::_SC_PAGESIZE) };
    if value <= 0 { 4096 } else { value as usize }
}

/// Change protection of `[addr, addr+len)`; `len` may be 0.
fn mprotect(addr: usize, len: usize, prot: libc::c_int) -> io::Result<()> {
    let ps = page_size();
    let start = addr & !(ps - 1);
    let end = addr
        .checked_add(len)
        .and_then(|v| v.checked_add(ps - 1))
        .map(|v| v & !(ps - 1))
        .ok_or_else(|| io::Error::from(io::ErrorKind::InvalidInput))?;
    // SAFETY: the range is page aligned and inside a mapped region.
    let rc = unsafe { libc::mprotect(start as *mut libc::c_void, end - start, prot) };
    if rc == 0 {
        Ok(())
    } else {
        Err(io::Error::last_os_error())
    }
}

const PROT_RX: libc::c_int = libc::PROT_READ | libc::PROT_EXEC;
const PROT_RW: libc::c_int = libc::PROT_READ | libc::PROT_WRITE;

/// Protection letter set (`rwx`) and path of the mapping containing `addr`,
/// read from `/proc/self/maps`. `None` when the address is not mapped.
pub fn protection_of(addr: usize) -> Option<String> {
    let text = std::fs::read_to_string("/proc/self/maps").ok()?;
    for line in text.lines() {
        let mut fields = line.split_whitespace();
        let range = fields.next()?;
        let perms = fields.next()?;
        let (start, end) = range.split_once('-')?;
        let (Ok(start), Ok(end)) = (
            usize::from_str_radix(start, 16),
            usize::from_str_radix(end, 16),
        ) else {
            continue;
        };
        if start <= addr && addr < end {
            // fields: offset, device, inode, path — the path is the 4th.
            let path = fields.nth(3).unwrap_or("");
            return Some(format!("{perms} {path}").trim_end().to_string());
        }
    }
    None
}

/// What the W^X window looked like, sampled from `/proc/self/maps`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct WxTrace {
    pub before: String,
    pub during: String,
    pub after: String,
}

impl WxTrace {
    /// `true` when the writable-and-executable state was never observable and
    /// the original protection was restored.
    pub fn is_wx_clean(&self) -> bool {
        let rwx = |state: &str| {
            let perms = state.split_whitespace().next().unwrap_or("");
            perms.contains('r') && perms.contains('w') && perms.contains('x')
        };
        !rwx(&self.before)
            && !rwx(&self.during)
            && !rwx(&self.after)
            && perms_of(&self.before) == perms_of(&self.after)
    }
}

fn perms_of(state: &str) -> &str {
    state.split_whitespace().next().unwrap_or("")
}

/// One enabler at a time: interleaved `mprotect` windows on the same driver
/// page would let one thread restore RX while the other is still writing.
static PATCH_IN_FLIGHT: std::sync::atomic::AtomicBool = std::sync::atomic::AtomicBool::new(false);

struct PatchGuard;

impl PatchGuard {
    fn acquire() -> Result<Self, BcnError> {
        if PATCH_IN_FLIGHT
            .compare_exchange(
                false,
                true,
                std::sync::atomic::Ordering::AcqRel,
                std::sync::atomic::Ordering::Acquire,
            )
            .is_err()
        {
            return Err(BcnError::Busy);
        }
        Ok(Self)
    }
}

impl Drop for PatchGuard {
    fn drop(&mut self) {
        PATCH_IN_FLIGHT.store(false, std::sync::atomic::Ordering::Release);
    }
}

/// Replace one executable instruction word under a strict W^X sequence.
///
/// `RX -> RW (no X) -> write -> instruction-cache sync -> RX`. The mapping is
/// never writable and executable at the same time (WC3-I-004: the previous
/// sequence asked for `PROT_READ|WRITE|EXEC`), and the write access is dropped on
/// every path out, including an `mprotect` failure on the way in (nothing was
/// written) and on the way out (reported as `Err`, never left writable).
///
/// # Safety
/// `addr` must be a 4-byte-aligned word inside this process's own executable
/// mapping, and no other thread may be executing that page for the duration
/// (see the crate quiescence policy in the module docs).
pub unsafe fn patch_code_word(addr: usize, word: u32) -> Result<WxTrace, BcnError> {
    if addr % 4 != 0 {
        return Err(BcnError::UnalignedWord);
    }
    let before = protection_of(addr).ok_or(BcnError::NotMapped)?;
    // Drop execute, add write: the only writable window, never executable.
    mprotect(addr, 4, PROT_RW).map_err(BcnError::Mprotect)?;
    let during = protection_of(addr).unwrap_or_else(|| "unmapped".to_string());
    // SAFETY: the caller guarantees the word is mapped and aligned; the page is
    // writable for exactly this store.
    unsafe { std::ptr::write_volatile(addr as *mut u32, word) };
    // SAFETY: the range was just written and is mapped.
    unsafe { aarch64::flush_icache(addr, addr + 4) };
    aarch64::isb();
    // Restore execute on every path: even when this fails the caller must not
    // keep a writable driver page, so the error is returned immediately.
    mprotect(addr, 4, PROT_RX).map_err(BcnError::Mprotect)?;
    let after = protection_of(addr).unwrap_or_else(|| "unmapped".to_string());
    Ok(WxTrace {
        before,
        during,
        after,
    })
}

/// Read a `u32` from executable memory.
///
/// # Safety
/// `addr..addr+4` must be readable.
unsafe fn read_word(addr: usize) -> u32 {
    // SAFETY: caller guarantees readability.
    unsafe { std::ptr::read_unaligned(addr as *const u32) }
}

/// Scan `[start, end)` for a `BL`; returns its address.
fn find_bl(start: usize, end: usize) -> Option<usize> {
    let mut pc = start;
    while pc + 4 <= end {
        // SAFETY: the caller made [start, end) readable.
        let word = unsafe { read_word(pc) };
        if word & 0xFC00_0000 == aarch64::BL {
            return Some(pc);
        }
        pc += 4;
    }
    None
}

/// Scan `[start, end)` for `needle`; returns its address.
fn find_word(start: usize, end: usize, needle: u32) -> Option<usize> {
    let mut pc = start;
    while pc + 4 <= end {
        // SAFETY: the caller made [start, end) readable.
        if unsafe { read_word(pc) } == needle {
            return Some(pc);
        }
        pc += 4;
    }
    None
}

fn map_fixed_noreplace(addr: usize, len: usize) -> io::Result<*mut libc::c_void> {
    // MAP_FIXED_NOREPLACE was added in Linux 4.17; Android 9 kernels predate it.
    const MAP_FIXED_NOREPLACE: libc::c_int = 0x10_0000;
    // SAFETY: anonymous private mapping at a page-aligned address. The page is
    // writable while the patch is assembled and becomes RX before anything can
    // branch to it, so the process never holds an RWX page.
    let mapped = unsafe {
        libc::mmap(
            addr as *mut libc::c_void,
            len,
            PROT_RW,
            libc::MAP_PRIVATE | libc::MAP_ANONYMOUS | MAP_FIXED_NOREPLACE,
            -1,
            0,
        )
    };
    if mapped != libc::MAP_FAILED {
        return Ok(mapped);
    }
    let error = io::Error::last_os_error();
    // EINVAL means the kernel does not know MAP_FIXED_NOREPLACE. Fall back to the
    // donor's MAP_FIXED only in that case; EEXIST is a real race and is reported.
    if error.raw_os_error() == Some(libc::EINVAL) {
        // SAFETY: same as above with the donor's flags.
        let mapped = unsafe {
            libc::mmap(
                addr as *mut libc::c_void,
                len,
                PROT_RW,
                libc::MAP_PRIVATE | libc::MAP_ANONYMOUS | libc::MAP_FIXED,
                -1,
                0,
            )
        };
        if mapped != libc::MAP_FAILED {
            return Ok(mapped);
        }
    }
    Err(error)
}

/// Patch a driver to expose BCn formats.
///
/// `function` must be the driver's own `vkGetPhysicalDeviceFormatProperties`
/// (obtained through the ICD's `vkGetInstanceProcAddr`, not through a loader
/// trampoline).
///
/// # Safety
/// Writes executable memory inside the current process. The caller must have
/// checked [`get_bcn_type`] == [`BcnType::Patch`] and must own the driver instance.
pub unsafe fn patch_bcn(function: *mut libc::c_void) -> Result<(), BcnError> {
    let _guard = PatchGuard::acquire()?;
    let function = function as usize;
    if function == 0 {
        return Err(BcnError::NullFunction);
    }
    let regions = proc_maps::read_self().map_err(BcnError::Maps)?;
    let region = proc_maps::containing(&regions, function).ok_or(BcnError::NotMapped)?;
    if !region.executable {
        return Err(BcnError::NotExecutable);
    }
    // Some drivers are mapped `--x`; make the whole text mapping readable first.
    mprotect(region.start, region.end - region.start, PROT_RX).map_err(BcnError::Mprotect)?;

    let bl_pc = find_bl(function, region.end).ok_or(BcnError::NoBranch)?;
    // SAFETY: bl_pc was found in a readable mapping.
    let bl_word = unsafe { read_word(bl_pc) };
    let conv = aarch64::decode_bl_target(bl_pc, bl_word).ok_or(BcnError::NoBranch)?;
    let conv_region = proc_maps::containing(&regions, conv).ok_or(BcnError::TargetNotMapped)?;
    if !conv_region.executable {
        return Err(BcnError::TargetNotExecutable);
    }
    mprotect(
        conv_region.start,
        conv_region.end - conv_region.start,
        PROT_RX,
    )
    .map_err(BcnError::Mprotect)?;

    let clear_result =
        find_word(conv, conv_region.end, CLEAR_RESULT_SIGNATURE).ok_or(BcnError::NoClearResult)?;

    let patch = generate_patch_bytes();
    let ps = page_size();
    if patch.len() > ps {
        return Err(BcnError::PatchTooLarge);
    }

    // Page next to the driver mapping.
    let mut page = proc_maps::find_free_page(&regions, function).ok_or(BcnError::NoFreePage)?;
    if page % ps != 0 {
        return Err(BcnError::UnalignedFreePage);
    }
    let mapped = match map_fixed_noreplace(page, ps) {
        Ok(ptr) => ptr,
        Err(_) => {
            // Re-read the maps once: another thread may have taken the hole.
            let fresh = proc_maps::read_self().map_err(BcnError::Maps)?;
            page = proc_maps::find_free_page(&fresh, function).ok_or(BcnError::NoFreePage)?;
            if page % ps != 0 {
                return Err(BcnError::UnalignedFreePage);
            }
            map_fixed_noreplace(page, ps).map_err(BcnError::MapFailed)?
        }
    };
    debug_assert_eq!(mapped as usize, page);

    // SAFETY: the page was just mapped RWX and is at least `patch.len()` bytes.
    unsafe {
        std::ptr::copy_nonoverlapping(patch.as_ptr(), mapped.cast::<u8>(), patch.len());
    }

    // Replace the fixup marker with a branch back to the instruction after the
    // patched default result.
    let words = patch.len() / 4;
    for index in 0..words {
        let slot = page + index * 4;
        // SAFETY: slot is inside the freshly written page.
        if unsafe { read_word(slot) } == PATCH_RETURN_FIXUP {
            let branch =
                aarch64::encode_b(slot, clear_result + 4).map_err(BcnError::BranchOutOfRange)?;
            // SAFETY: writing inside our own mapped page.
            unsafe { std::ptr::write_unaligned(slot as *mut u32, branch) };
        }
    }

    // The patch page holds only data until this point; seal it RX before any
    // branch can target it. Its instructions enter the icache now, while no
    // branch reaches it yet.
    mprotect(page, ps, PROT_RX).map_err(BcnError::Mprotect)?;
    // SAFETY: the page is mapped and `patch.len()` bytes were written above.
    unsafe { aarch64::flush_icache(page, page + patch.len()) };
    aarch64::isb();

    let branch_to_patch =
        aarch64::encode_b(clear_result, page).map_err(BcnError::BranchOutOfRange)?;

    // The one driver word we rewrite: RX -> RW (no X) -> write -> icache sync ->
    // RX, never RWX (WC3-I-004). The trace is sampled from `/proc/self/maps` at
    // each stage; the probe example prints it.
    // SAFETY: `clear_result` was found inside the driver's executable mapping,
    // and the enabler holds the process-wide patch guard.
    let trace = unsafe { patch_code_word(clear_result, branch_to_patch)? };
    debug_assert!(
        trace.is_wx_clean(),
        "code patch must not expose an rwx mapping: {trace:?}"
    );
    Ok(())
}

