#!/usr/bin/env python3
"""Generate `crates/wc3-sim/src/combat_gen.rs` from the shipped War3 unit data.

Sources (read-only extracts already in the repository):

* ``analysis/war3_full/Units/UnitWeapons.slk``  — ``targs1/2``, splash radii and
  factors (``Farea1/Harea1/Qarea1/Hfact1/Qfact1/splashTargs1/targCount1``).
* ``analysis/war3_full/Units/UnitBalance.slk``  — row presence only; the
  bounty table itself lives in `bounty_gen.rs` (`data::unit_bounty`).
* ``analysis/war3_full/Units/UnitData.slk``     — ``targType`` (the unit's own
  target class).

``roster_gen.rs`` is generated from ``war3_full``; ``creeps_gen.rs`` and
``extras_gen.rs`` are generated from ``war3x_data``, so those ids read the same
extract their stats come from (with a fallback to the other extract).

Unit ids are collected from the generated def tables the simulation actually
compiles in, so the profile table stays in lockstep with the roster.

Usage: ``python3 crates/wc3-sim/tools/gen_combat.py`` (writes the file, prints
a summary).  The output must stay sorted by id: the runtime lookup is a binary
search.
"""

from __future__ import annotations

import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from slkread import as_float, as_int, index_by_id, read_slk_rows  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
CRATE = os.path.dirname(HERE)
REPO = os.path.dirname(os.path.dirname(CRATE))
ANALYSIS = os.path.join(REPO, "analysis")

EXTRACTS = {
    "roc": os.path.join(ANALYSIS, "war3_full", "Units"),
    "tft": os.path.join(ANALYSIS, "war3x_data", "Units"),
}

TARGET_TOKENS = [
    "GROUND", "AIR", "STRUCTURE", "WARD", "DEBRIS", "ITEM", "TREE", "WALL", "ENEMY",
]

# Mirror of `combat::tg` — the generator emits the constant names and the
# runtime derives their values; a mismatch fails `combat_target_bits_match`.
TOKEN_BITS = {name: 1 << index for index, name in enumerate(TARGET_TOKENS)}

# `@generated by ...` header marker used to detect the file is not hand edited.
HEADER = '''// @generated by crates/wc3-sim/tools/gen_combat.py -- do not edit by hand.
// Sources: analysis/war3_full/Units/{UnitWeapons,UnitBalance,UnitData}.slk and
// analysis/war3x_data/Units/*.slk (TFT-only neutral defs), access 2026-11-15.
//
// `weapon_targs` is the union of the two shipped weapons (`targs1`|`targs2`):
// the sim models one weapon, and dual-weapon units (mortar team, catapult, ...)
// split ground and structure targets between them.
// `splash` carries the shipped splash falloff (Farea/Harea/Qarea + Hfact/Qfact).
'''


def load_extract(name):
    units = os.path.join(EXTRACTS[name], "Units") if False else EXTRACTS[name]
    _, weap_rows = read_slk_rows(os.path.join(units, "UnitWeapons.slk"))
    _, bal_rows = read_slk_rows(os.path.join(units, "UnitBalance.slk"))
    _, data_rows = read_slk_rows(os.path.join(units, "UnitData.slk"))
    return {
        "weapons": index_by_id(weap_rows),
        "balance": index_by_id(bal_rows),
        "data": index_by_id(data_rows),
    }


def tokens(value):
    if value is None:
        return []
    return [
        token.strip()
        for token in str(value).split(",")
        if token.strip() not in ("", "-", "_", " - ")
    ]


def mask(value):
    bits = 0
    for token in tokens(value):
        bits |= TOKEN_BITS.get(token.strip().upper(), 0)
    return bits


def mask_expr(bits):
    if bits == 0:
        return "0"
    names = [name for name in TARGET_TOKENS if bits & TOKEN_BITS[name]]
    return " | ".join(names)


def serial_ids():
    """Unit ids per generated def table, in the order the crate uses them."""
    groups = {}
    for file_name in ("roster_gen.rs", "creeps_gen.rs", "shops_gen.rs", "extras_gen.rs"):
        path = os.path.join(CRATE, "src", file_name)
        text = open(path, encoding="utf-8").read()
        groups[file_name] = re.findall(r'^        id: "([^"]+)",$', text, re.M)
    return groups


def splash_profile(weapon):
    full = as_float(weapon.get("Farea1"), 0.0)
    if full <= 0.0:
        return None
    half = as_float(weapon.get("Harea1"), full)
    quarter = as_float(weapon.get("Qarea1"), half)
    if half <= 0.0:
        half = full
    if quarter <= 0.0:
        quarter = half
    # `Hfact1`/`Qfact1` are shipped fractions (0.4, 0.1); WC3's defaults are
    # 0.5/0.25 when a map leaves them blank.
    half_factor = round(as_float(weapon.get("Hfact1"), 0.5) * 1000)
    quarter_factor = round(as_float(weapon.get("Qfact1"), 0.25) * 1000)
    half_factor = max(0, min(1000, half_factor))
    quarter_factor = max(0, min(1000, quarter_factor))
    count = as_int(weapon.get("targCount1"), 0)
    targs = mask(weapon.get("splashTargs1"))
    return (full, half, quarter, half_factor, quarter_factor, count, targs)


def main():
    roc = load_extract("roc")
    tft = load_extract("tft")
    groups = serial_ids()

    rows = []
    missing = []
    seen = set()
    for file_name, ids in groups.items():
        extract = roc if file_name in ("roster_gen.rs", "shops_gen.rs") else tft
        fallback = tft if extract is roc else roc
        for unit_id in ids:
            if unit_id in seen:
                continue
            seen.add(unit_id)
            balance = extract["balance"].get(unit_id) or fallback["balance"].get(unit_id)
            weapon = extract["weapons"].get(unit_id) or fallback["weapons"].get(unit_id)
            data = extract["data"].get(unit_id) or fallback["data"].get(unit_id)
            if balance is None and weapon is None and data is None:
                missing.append(unit_id)
                continue
            balance = balance or {}
            weapon = weapon or {}
            data = data or {}

            unit_class = mask(data.get("targType"))
            if unit_class == 0:
                unit_class = TOKEN_BITS["STRUCTURE"] if as_int(balance.get("HP")) and data.get(
                    "type") == "bldg" else TOKEN_BITS["GROUND"]

            weapon_targs = mask(weapon.get("targs1"))
            # Weapon 2 carries the structure half of dual-weapon units
            # (mortar team: ground in weapon 1, structure in weapon 2).
            weapon2_damage = as_int(weapon.get("dmgplus2"), 0) + as_int(
                weapon.get("dice2"), 0)
            if weapon2_damage > 0:
                weapon_targs |= mask(weapon.get("targs2"))
            if weapon_targs == 0 and as_int(weapon.get("dmgplus1"), 0) > 0:
                weapon_targs = TOKEN_BITS["GROUND"]

            splash = splash_profile(weapon)

            rows.append((unit_id, weapon_targs, unit_class, splash))

    rows.sort(key=lambda row: row[0])

    lines = [HEADER]
    lines.append('')
    lines.append('use crate::combat::tg::{')
    lines.append('    ' + ', '.join(name for name in TARGET_TOKENS))
    lines.append('};')
    lines.append('')
    lines.append('/// Splash falloff from `UnitWeapons.slk` '
                 '(`Farea1`/`Harea1`/`Qarea1`, `Hfact1`/`Qfact1`, `targCount1`).')
    lines.append('#[derive(Debug, Clone, Copy, PartialEq)]')
    lines.append('pub struct SplashProfile {')
    lines.append('    /// Full-damage radius (`Farea1`), world units.')
    lines.append('    pub full_radius: f32,')
    lines.append('    /// Half-damage radius (`Harea1`), world units.')
    lines.append('    pub half_radius: f32,')
    lines.append('    /// Quarter-damage radius (`Qarea1`), world units.')
    lines.append('    pub quarter_radius: f32,')
    lines.append('    /// Damage factor inside `half_radius`, permille (`Hfact1`).')
    lines.append('    pub half_factor: i32,')
    lines.append('    /// Damage factor inside `quarter_radius`, permille (`Qfact1`).')
    lines.append('    pub quarter_factor: i32,')
    lines.append('    /// Maximum splash targets (`targCount1`); 0 means unlimited.')
    lines.append('    pub max_targets: u8,')
    lines.append('    /// `splashTargs1` mask; 0 inherits the weapon targets.')
    lines.append('    pub targs: u16,')
    lines.append('}')
    lines.append('')
    lines.append('/// Per-unit combat data from the shipped object tables.')
    lines.append('#[derive(Debug, Clone, Copy, PartialEq)]')
    lines.append('pub struct CombatProfile {')
    lines.append('    pub id: &\'static str,')
    lines.append('    /// Union of `targs1` and `targs2`.')
    lines.append('    pub weapon_targs: u16,')
    lines.append('    /// `UnitData.slk:targType` — the unit\'s own target class.')
    lines.append('    pub unit_class: u16,')
    lines.append('    pub splash: Option<SplashProfile>,')
    lines.append('}')
    lines.append('')
    lines.append('pub static PROFILES: &[CombatProfile] = &[')
    for (unit_id, weapon_targs, unit_class, splash) in rows:
        if splash is None:
            splash_expr = 'None'
        else:
            full, half, quarter, half_factor, quarter_factor, count, targs = splash
            splash_expr = (
                'Some(SplashProfile { '
                f'full_radius: {full:.1f}, half_radius: {half:.1f}, '
                f'quarter_radius: {quarter:.1f}, '
                f'half_factor: {half_factor}, quarter_factor: {quarter_factor}, '
                f'max_targets: {min(count, 255)}, targs: {mask_expr(targs)} }})'
            )
        lines.append(
            '    CombatProfile { '
            f'id: "{unit_id}", '
            f'weapon_targs: {mask_expr(weapon_targs)}, '
            f'unit_class: {mask_expr(unit_class)}, splash: {splash_expr} }},'
        )
    lines.append('];')
    lines.append('')
    lines.append('/// Binary search over the id-sorted table.')
    lines.append("pub fn profile(id: &str) -> Option<&'static CombatProfile> {")
    lines.append('    PROFILES')
    lines.append('        .binary_search_by(|probe| probe.id.cmp(id))')
    lines.append('        .ok()')
    lines.append('        .map(|index| &PROFILES[index])')
    lines.append('}')
    lines.append('')

    out_path = os.path.join(CRATE, "src", "combat_gen.rs")
    with open(out_path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))

    splash_rows = sum(1 for row in rows if row[3] is not None)
    print(f"wrote {out_path}")
    print(f"profiles={len(rows)} splash={splash_rows} missing={len(missing)}")
    if missing:
        print("missing ids:", ", ".join(sorted(missing)[:20]))


if __name__ == "__main__":
    main()
